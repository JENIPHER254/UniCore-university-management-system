import fs from "node:fs";
import os from "node:os";
import path from "node:path";
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "unicore-dbg-"));
process.env.DATABASE_PATH = path.join(tmp, "debug.db");
const { setupTestDatabase, makeUser } = await import("./helpers.js");
const { startServer, http, login } = await import("./http.js");
const db = setupTestDatabase(process.env.DATABASE_PATH!);
makeUser(db, "admin@t.local", "A", "administrator", "Passw0rd123");
await startServer();
const token = (await login("admin@t.local", "Passw0rd123")).body.token;
const prog = await http("POST", "/api/programmes", { token, json: { code: "PRG1", name: "Programme X1" } });
const student = await http("POST", "/api/students", { token, json: { firstName: "S", lastName: "B", email: "sb@t.local", programmeId: prog.body.id, admissionDate: "2026-02-01" } });
console.log("student:", student.status, student.body.id);
const c1 = await http("POST", "/api/finance/charges", { token, json: { studentId: student.body.id, description: "C1", amount: "500.00", chargeDate: "2026-01-01" } });
console.log("c1:", c1.status, JSON.stringify(c1.body).slice(0, 200));
const c2 = await http("POST", "/api/finance/charges", { token, json: { studentId: student.body.id, description: "C2", amount: "300.00", chargeDate: "2026-02-01" } });
console.log("c2:", c2.status, JSON.stringify(c2.body).slice(0, 200));
const pay = await http("POST", "/api/finance/payments", { token, json: { studentId: student.body.id, amount: "650.00", paymentDate: "2026-03-05" } });
console.log("pay:", pay.status, JSON.stringify(pay.body).slice(0, 200));
const profile = await http("GET", `/api/finance/students/${student.body.id}/profile`, { token });
console.log("profile:", profile.status, JSON.stringify(profile.body.charges).slice(0, 400));
console.log("totals:", JSON.stringify(profile.body.totals));
process.exit(0);
